"""Report renderers: JSON, Markdown, HTML (Jinja2) and PDF (WeasyPrint), in a
technical or executive style.
"""
from __future__ import annotations

import json
import re

from .model import ReportData, priority_of

SCHEMA = "autopwn.report/1"
_PURPLE = "🔵"


def to_json(data: ReportData, *, indent: int = 2) -> str:
    doc = {
        "schema": SCHEMA,
        "tool": {"name": data.meta.tool, "version": data.meta.version},
        "run": {
            "id": data.meta.run_id, "goal": data.meta.goal,
            "targets": data.meta.targets, "profile": data.meta.profile,
            "generated_at": data.meta.generated_at,
        },
        "summary": {
            "total": data.total,
            "top_severity": data.top_severity,
            "by_severity": data.counts,
            "by_owasp": data.by_owasp,
            "suspected_not_reported": data.suspected_count,
        },
        "findings": data.rows(),
    }
    return json.dumps(doc, indent=indent, ensure_ascii=False, default=str)


def to_markdown(data: ReportData) -> str:
    m = data.meta
    L: list[str] = []
    L.append(f"# {m.title}")
    L.append("")
    L.append(f"**Run:** `{m.run_id}`  ·  **Generated:** {m.generated_at}  ·  "
             f"**Profile:** {m.profile}")
    L.append(f"**Targets:** {', '.join(m.targets) or '—'}")
    if m.goal:
        L.append(f"**Objective:** {m.goal}")
    L.append("")
    L.append("## Summary")
    L.append("")
    c = data.counts
    L.append(f"**{data.total} verified finding(s)** — "
             f"{c['critical']} critical · {c['high']} high · {c['medium']} medium · "
             f"{c['low']} low · {c['info']} info.")
    if data.suspected_count:
        L.append(f"_({data.suspected_count} suspected item(s) could not be safely "
                 f"verified and are intentionally excluded — the false-positive filter.)_")
    L.append("")
    L.append("| # | Priority | Severity | CVSS | Finding | Location |")
    L.append("|---|---|---|---|---|---|")
    for i, f in enumerate(data.findings, 1):
        where = f.target.url or f.target.host
        if f.target.param:
            where += f" (`{f.target.param}`)"
        L.append(f"| {i} | {priority_of(f)} | {f.severity.rating.value} | "
                 f"{f.severity.cvss_score} | {f.title} | {where} |")
    L.append("")
    L.append("## Findings")
    for i, f in enumerate(data.findings, 1):
        L.append("")
        L.append(f"### {i}. {f.title}  — {f.severity.rating.value.upper()} "
                 f"(CVSS {f.severity.cvss_score}, {priority_of(f)})")
        L.append("")
        L.append(f"- **Target:** {f.target.url or f.target.host}"
                 + (f" · param `{f.target.param}`" if f.target.param else ""))
        meta_bits = [b for b in (f.owasp, f.cwe) if b]
        if meta_bits:
            L.append(f"- **Mapping:** {' · '.join(meta_bits)}")
        if f.severity.cvss_vector:
            L.append(f"- **CVSS vector:** `{f.severity.cvss_vector}`")
        L.append(f"- **Status:** {f.status.value} · confidence {f.confidence:.0%}")
        if f.safe_poc:
            L.append(f"- **Safe proof:** {f.safe_poc}")
        if data.style != "executive":
            if f.evidence.request:
                L.append(f"- **Request:** `{_oneline(f.evidence.request)}`")
            if f.evidence.response:
                L.append("- **Response (excerpt):**")
                L.append("  ```")
                L.append("  " + _oneline(f.evidence.response)[:500])
                L.append("  ```")
            if f.evidence.steps:
                L.append("- **Steps:** " + " → ".join(f.evidence.steps))
        L.append(f"- {_PURPLE} **Detection (blue team):** {f.detection_guidance}")
        L.append(f"- {_PURPLE} **Remediation:** {f.remediation}")
    L.append("")
    L.append(f"---\n_Generated by {m.tool} {m.version} · non-destructive, "
             f"safe-verification only._")
    return "\n".join(L)


def _oneline(s: str) -> str:
    return " ".join((s or "").split())


_STYLES = {"technical", "executive"}


def _env():
    from pathlib import Path

    from jinja2 import Environment, FileSystemLoader, select_autoescape

    from .model import priority_of
    env = Environment(
        loader=FileSystemLoader(str(Path(__file__).parent / "templates")),
        autoescape=select_autoescape(["html"]),
    )
    env.filters["priority"] = priority_of
    return env


def to_html(data: ReportData) -> str:
    style = data.style if data.style in _STYLES else "technical"
    env = _env()
    return env.get_template(f"{style}.html").render(data=data)


_SARIF_LEVEL = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}


def to_sarif(data: ReportData) -> str:
    """SARIF 2.1.0 — readable by GitHub code scanning, Azure DevOps, DefectDojo and
    most CI security dashboards. One rule per finding class/title, one result each."""
    from .. import __version__
    rules: dict[str, dict] = {}
    results = []
    for f in data.findings:
        rule_id = re.sub(r"[^A-Za-z0-9_.-]+", "-", f.title).strip("-").lower() or f.id
        rules.setdefault(rule_id, {
            "id": rule_id, "name": f.title,
            "shortDescription": {"text": f.title},
            "fullDescription": {"text": f.safe_poc or f.title},
            "help": {"text": f"Remediation: {f.remediation}\nDetection: {f.detection_guidance}",
                     "markdown": f"**Remediation** — {f.remediation}\n\n**Detection** — {f.detection_guidance}"},
            "properties": {"tags": [t for t in ("security", f.cwe, f.owasp) if t],
                           "security-severity": f"{f.severity.cvss_score:.1f}"},
        })
        uri = f.target.url or f"https://{f.target.host}/"
        results.append({
            "ruleId": rule_id,
            "level": _SARIF_LEVEL.get(f.severity.rating.value, "warning"),
            "message": {"text": f"{f.title} on {f.target.url or f.target.host}"
                                + (f" (parameter {f.target.param})" if f.target.param else "")},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": uri}}}],
            "partialFingerprints": {"autopwnFindingId": f.id},
            "properties": {"cvss": f.severity.cvss_score, "cvssVector": f.severity.cvss_vector,
                           "status": f.status.value, "confidence": f.confidence},
        })
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": "AutoPwn AI", "version": __version__,
                                "informationUri": "https://github.com/AshrafMostafaNmap/autopwn-ai",
                                "rules": list(rules.values())}},
            "automationDetails": {"id": f"autopwn/{data.meta.run_id}"},
            "results": results,
        }],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False)


class PDFUnavailable(RuntimeError):
    """WeasyPrint (and its system libs) are not available."""


def pdf_available() -> bool:
    try:
        import weasyprint  # noqa: F401
        return True
    except Exception:
        return False


def to_pdf(data: ReportData) -> bytes:
    """Render the HTML report to PDF bytes. Raises PDFUnavailable if WeasyPrint
    (or its native deps) can't load — callers fall back to HTML."""
    try:
        from weasyprint import HTML
    except Exception as e:                           # missing lib or native deps
        raise PDFUnavailable(
            "PDF needs WeasyPrint. Install with `pip install autopwn-ai[pdf]` "
            f"(plus its system libraries: pango, cairo). import failed: {e}"
        ) from e
    html = to_html(data)
    return HTML(string=html).write_pdf()
